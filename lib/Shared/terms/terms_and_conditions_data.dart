/// Structured content for the Rasikh platform legal documents.
///
/// The text below is the official Arabic wording of the platform's terms
/// and conditions. It is split into two documents:
///   1. Terms & conditions for clients (18 articles).
///   2. Service provider agreement (24 articles).
///
/// Keeping the wording in a data model (instead of one long string) lets the
/// UI render a professional, navigable legal document with numbered articles,
/// definitions and a table of contents.
library;

class TermsClause {
  const TermsClause(
    this.text, {
    this.term,
    this.numbered = true,
  }) : assert(
          term == null || !numbered,
          'A definition cannot be a numbered clause.',
        );

  /// A plain paragraph that is not part of a numbered list.
  const TermsClause.paragraph(this.text)
      : term = null,
        numbered = false;

  /// A `term : definition` entry, used by the definitions articles.
  const TermsClause.definition(this.term, this.text) : numbered = false;

  /// The clause wording.
  final String text;

  /// The defined term, when this clause is a definition.
  final String? term;

  /// Whether the clause should display an incremental number.
  final bool numbered;
}

class TermsArticle {
  const TermsArticle({
    required this.number,
    required this.title,
    required this.clauses,
    this.intro,
  });

  /// Article number, starting at 1.
  final int number;

  /// Article subject, e.g. "التعريفات".
  final String title;

  /// Optional introductory sentence shown before the clauses.
  final String? intro;

  final List<TermsClause> clauses;
}

class TermsDocument {
  const TermsDocument({
    required this.preamble,
    required this.articles,
  });

  /// Introduction paragraphs shown in the "المقدمة" card.
  final List<String> preamble;

  final List<TermsArticle> articles;
}

